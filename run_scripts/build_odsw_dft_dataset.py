        "ENCUT = 520",
        "EDIFF = 1E-6",
        "EDIFFG = -0.02",
        "ISMEAR = 1",
        "SIGMA = 0.2",
        "IBRION = 2",
        "NSW = 100",
        "ISIF = 2",
        "LREAL = Auto",
        "ALGO = Normal",
        "LASPH = .TRUE.",
        "LWAVE = .FALSE.",
